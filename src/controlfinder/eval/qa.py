"""`make qa`: checks the question set for Phases 4 and 5 and writes a sheet for reviewing it.

data/eval/qa.jsonl holds 100 practitioner questions. 60 can be answered from SP 800-53, and each
lists the base controls a good answer cites. 40 can't (pre-registered definition 1), 8 of each
kind: they need another framework's text, one organization's own facts, a legal conclusion,
general trivia, or security facts the catalog doesn't hold. An agent drafted the labels from the
catalog alone, without running retrieval on any question, and Jude corrects them: his label is
final.

The split is 50/50 within each category, in the same seeded hash order as the gold set, so dev
and test both get 30 answerable questions and 4 of each unanswerable kind. It's computed from the
IDs on every load rather than stored, and results/qa_stats.json lists both sides, so a change to
the split shows up in the diff. Writes data/eval/qa_review.md and results/qa_stats.json.
"""

import hashlib
import json
import os
from collections import Counter, defaultdict
from dataclasses import dataclass, fields
from pathlib import Path
from statistics import median

from controlfinder.eval.goldset import SEED, UNSEAL
from controlfinder.ingest.ids import display_id, parent_control_id
from controlfinder.ingest.oscal import parse_catalog
from controlfinder.ingest.sources import CATALOG, fetch

QA = Path("data/eval/qa.jsonl")
REVIEW = Path("data/eval/qa_review.md")
STATS = Path("results/qa_stats.json")
DEV_SHARE = 0.5
UNANSWERABLE = ("other_framework", "internal_policy", "legal", "trivia", "security_specifics")
CATEGORIES = ("answerable", *UNANSWERABLE)


@dataclass(frozen=True)
class Question:
    id: str  # 'q001'
    question: str
    answerable: bool
    gold: tuple[str, ...]  # base control IDs, sorted; empty when unanswerable
    category: str  # 'answerable' or one of UNANSWERABLE
    why: str  # the reason for the label, for the reviewer
    split: str  # 'dev' or 'test'


def check(row: dict) -> None:
    """Raises unless the row's keys, category, answerable flag and gold labels agree."""
    keys = [f.name for f in fields(Question) if f.name != "split"]
    if sorted(row) != sorted(keys):
        raise ValueError(f"{row.get('id')}: expected keys {keys}, found {list(row)}")
    if row["category"] not in CATEGORIES:
        raise ValueError(f"{row['id']}: unknown category {row['category']!r}")
    if not row["answerable"] == (row["category"] == "answerable") == bool(row["gold"]):
        raise ValueError(f"{row['id']}: an answerable question has category 'answerable' and gold labels, others neither")
    if len(set(row["gold"])) != len(row["gold"]):
        raise ValueError(f"{row['id']}: repeated gold label")
    for control_id in row["gold"]:
        if parent_control_id(control_id) != control_id:
            raise ValueError(f"{row['id']}: gold label {control_id!r} isn't a base control ID in OSCAL form ('ac-2')")


def split_questions(rows: list[dict]) -> dict[str, str]:
    """'dev' or 'test' for each question: 50/50 within each category, in seeded hash order."""
    by_category = defaultdict(list)
    for row in rows:
        by_category[row["category"]].append(row["id"])
    split = {}
    for ids in by_category.values():
        ids.sort(key=lambda qid: hashlib.sha256(f"{SEED}:{qid}".encode()).hexdigest())
        n_dev = round(DEV_SHARE * len(ids))
        split |= {qid: "dev" if i < n_dev else "test" for i, qid in enumerate(ids)}
    return split


def read_questions(path: Path = QA) -> list[Question]:
    """Every question with its split. Raises on a row that breaks the labelling rules."""
    rows = [json.loads(line) for line in path.read_text().splitlines()]
    for row in rows:
        check(row)
    for key in ("id", "question"):
        if repeated := [value for value, n in Counter(row[key].strip().lower() for row in rows).items() if n > 1]:
            raise ValueError(f"repeated {key}: {repeated}")
    split = split_questions(rows)
    return [Question(**{**row, "gold": tuple(sorted(row["gold"])), "split": split[row["id"]]}) for row in rows]


def load_questions(split: str, path: Path = QA) -> list[Question]:
    """One split of the question set. The test split stays sealed until the Phase 6 run."""
    if split == "test" and os.environ.get(UNSEAL) != "1":
        raise PermissionError(f"the test split is sealed; only the final Phase 6 run sets {UNSEAL}=1")
    return [q for q in read_questions(path) if q.split == split]


def review_sheet(questions: list[Question], titles: dict[str, str]) -> str:
    def cell(text: str) -> str:
        return text.replace("|", "\\|")

    lines = [
        "# Question set: review sheet",
        "",
        f"Generated by `make qa` from `{QA}`. Edit that file, not this one, then re-run `make qa`.",
        "",
        "## Answerable",
        "",
        "| ID | Split | Question | Gold controls | Why |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| {q.id} | {q.split} | {cell(q.question)} | "
              f"{'<br>'.join(f'{display_id(c)} {titles[c]}' for c in q.gold)} | {cell(q.why)} |"
              for q in questions if q.answerable]
    lines += ["", "## Unanswerable", "", "| ID | Split | Category | Question | Why |", "|---|---|---|---|---|"]
    lines += [f"| {q.id} | {q.split} | {q.category} | {cell(q.question)} | {cell(q.why)} |"
              for q in questions if not q.answerable]
    return "\n".join(lines) + "\n"


def main() -> None:
    controls, _ = parse_catalog(json.loads(fetch(CATALOG).read_text())["catalog"])
    titles = {c.id: c.title for c in controls if not c.is_enhancement}
    questions = read_questions()
    if unknown := sorted({c for q in questions for c in q.gold} - set(titles)):
        raise ValueError(f"gold labels that aren't active base controls: {unknown}")

    REVIEW.write_text(review_sheet(questions, titles))
    per_split = {name: [q for q in questions if q.split == name] for name in ("dev", "test")}
    sizes = [len(q.gold) for q in questions if q.answerable]
    gold = {c for q in questions for c in q.gold}
    stats = {
        "source": {"path": str(QA), "sha256": hashlib.sha256(QA.read_bytes()).hexdigest()},
        "questions": len(questions),
        "by_category": {category: {name: sum(q.category == category for q in qs) for name, qs in per_split.items()}
                        for category in CATEGORIES},
        "gold_set_size": {"min": min(sizes), "median": median(sizes), "max": max(sizes)},
        "distinct_gold_controls": len(gold),
        "families_in_gold": len({c.split("-")[0] for c in gold}),
        "split": {"unit": "question", "stratified_by": "category", "seed": SEED, "dev_share": DEV_SHARE,
                  **{name: [q.id for q in qs] for name, qs in per_split.items()}},
    }
    STATS.write_text(json.dumps(stats, indent=2) + "\n")

    for name, qs in per_split.items():
        print(f"{name}: {sum(q.answerable for q in qs)} answerable, {sum(not q.answerable for q in qs)} unanswerable")
    print(f"{len(gold)} distinct gold controls from {stats['families_in_gold']} families; "
          f"gold set size {min(sizes)}-{max(sizes)}")
    print(f"wrote {REVIEW} and {STATS}")


if __name__ == "__main__":
    main()
